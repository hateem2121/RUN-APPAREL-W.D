/**
 * Generate `src/lib/dialCodes.ts`: every country the contact form offers, with its phone
 * code (owner, 2026-09-29: pick a country, the code fills itself in, and stays editable).
 *
 * WHY GENERATED, NOT IMPORTED. `libphonenumber-js` is the maintained source of calling codes
 * (Google's libphonenumber metadata), but the form needs only a code per country: 12,549
 * bytes of source for 245 countries, against 83,892 bytes for the library's smallest
 * metadata (both measured 2026-09-29). So the library is a dev dependency and nothing of it
 * reaches a visitor; the table is committed, and a regenerated table is a reviewable diff.
 *
 * English names come from `Intl.DisplayNames`, so no second hand-typed list exists to drift.
 *
 * Run: node apps/cms/scripts/build-dial-codes.mjs   (then Biome formats the output)
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getCountries, getCountryCallingCode } from 'libphonenumber-js'

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'dialCodes.ts')
const names = new Intl.DisplayNames(['en'], { type: 'region' })

const countries = getCountries()
  .map((code) => ({ code, name: names.of(code) ?? code, dial: getCountryCallingCode(code) }))
  // A region Intl cannot name comes back as its own code; a list of "AC" helps nobody.
  .filter((country) => country.name !== country.code)
  .sort((a, b) => a.name.localeCompare(b.name, 'en'))

const rows = countries
  .map((c) => `  { code: '${c.code}', name: ${JSON.stringify(c.name)}, dial: '${c.dial}' },`)
  .join('\n')

writeFileSync(
  out,
  `/**
 * GENERATED by apps/cms/scripts/build-dial-codes.mjs — do not edit by hand; re-run it.
 * Calling codes from libphonenumber-js; English names from Intl.DisplayNames.
 */
export type Country = { code: string; name: string; dial: string }

export const COUNTRIES: readonly Country[] = [
${rows}
]
`,
)
console.log(`[dial-codes] ${countries.length} countries → ${out}`)
