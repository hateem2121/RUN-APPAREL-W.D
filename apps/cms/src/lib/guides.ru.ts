/** The garment pages' weight bands (`WEIGHT_BANDS`), in Russian; a band missing here throws. */
const WEIGHT_BAND_RU: Readonly<Record<string, string>> = {
  'very light and thin': 'очень лёгкая и тонкая ткань',
  'light, an easy layer': 'лёгкая, удобна для носки в несколько слоёв',
  'mid-weight, solid yet easy to move in': 'средняя: плотная, но не сковывает движений',
  'heavier, sturdy and hard-wearing': 'более тяжёлая, крепкая и износостойкая',
  'heavy and thick, for warmth': 'тяжёлая и толстая, для тепла',
}

const WEIGHT_BAND_TEXT_RU = WEIGHT_BANDS.map((entry, index) => {
  const band = WEIGHT_BAND_RU[entry.band]
  if (!band) throw new Error(`guides.ru.ts: no Russian words for the weight band "${entry.band}"`)
  const from = WEIGHT_BANDS[index - 1]?.below
  if (from === undefined) return `Ниже ${entry.below} г/м² — ${band}.`
  if (!Number.isFinite(entry.below)) return `От ${from} и выше — ${band}.`
  return `От ${from} до ${entry.below} — ${band}.`
}).join(' ')

/** `ballSizeRange` (`guideTools.ts`) in Russian, from the same list, so table and tool agree. */
function ballSizeRangeRu(country: BallCountry, size: 3 | 4 | 5): string {
  const groups = BALL_SIZES[country].filter((entry) => entry.size === size).map((e) => e.group)
  const first = groups[0]
  const last = groups[groups.length - 1]
  if (first === undefined || last === undefined) return ''
  if (groups.length === 1) return ballGroupRu(first)
  if (groups.length === 2) return `${ballGroupRu(first)}, ${ballGroupRu(last)}`
  return `${ballGroupRu(first)} — ${ballGroupRu(last)}`
}

