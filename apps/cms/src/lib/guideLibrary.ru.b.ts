/** An English topic with no Russian words shows in English, so the Cyrillic check names it. */
const ruQuestion = (topic: string) =>
  BUYER_QUESTIONS_RU[topic] ?? { topic, rule: topic, guide: topic }

const FEWER_THAN_RU = `меньше ${SMALL_COUNT}`

const countCellRu = (count: number | null): string => {
  if (count === null) return COUNT_GAP
  return count < SMALL_COUNT ? FEWER_THAN_RU : String(count)
}

const shareCellRu = (count: number | null, total: number | null): string => {
  if (count === null || total === null) return COUNT_GAP
  if (count < SMALL_COUNT) return FEWER_THAN_RU
  const tenths = Math.round((count / total) * 1000) / 10
  return `${String(tenths).replace('.', ',')}%`
}

const buyerQuestionRowsRu = (): string[][] => [
  ...BUYER_QUESTIONS.map((row) => {
    const ru = ruQuestion(row.topic)
    return [ru.topic, countCellRu(row.count), shareCellRu(row.count, TOTAL_INQUIRIES), ru.guide]
  }),
  ['Все учтённые запросы', countCellRu(TOTAL_INQUIRIES), '100%', ''],
]

const buyerQuestionLinksRu = (): GuideLink[] => {
  const seen = new Map<string, GuideLink>()
  for (const row of BUYER_QUESTIONS) {
    const label = ruQuestion(row.topic).guide
    seen.set(label, { phrase: label, href: row.guide.path })
  }
  return [...seen.values()]
}

const buyerRuleRowsRu = (): string[][] =>
  BUYER_QUESTIONS.map((row) => [ruQuestion(row.topic).topic, ruQuestion(row.topic).rule])

