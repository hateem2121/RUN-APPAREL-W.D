/**
 * The Russian twin of `LIBRARY_GUIDES` 10–19 (guideLibrary.ts), in the same order and at the same
 * paths. The structure must match the English entry for entry: the same sections, blocks, list and
 * table sizes, links, photos, stages, garments and sources. Only the prose is translated. A figure
 * the English reads from a constant is read from the same constant here; a helper that returns
 * English words is rewritten below in Russian, still reading its figures from the same place.
 */
const fact = (prefix: string): string =>
  FACTS.find((entry) => entry.label.startsWith(prefix))?.value ?? ''

const MINIMUM = fact('Minimum')

/** Russian plural form for a count: one, few (2–4), many. */
const plural = (count: number, one: string, few: string, many: string): string => {
  const tens = count % 100
  const units = count % 10
  if (tens >= 11 && tens <= 14) return many
  if (units === 1) return one
  if (units >= 2 && units <= 4) return few
  return many
}

